def create_app(
    service_factory: Callable[[], AssistantService] | None = None,
) -> FastAPI:
    """应用工厂；模型服务延迟初始化，健康检查不会触发模型加载。"""

    app = FastAPI(
        title="PersonaX Assistant API",
        version=API_VERSION,
        description="本地 Agent 问答 JSON/SSE 接口；不包含真实发布能力。",
        docs_url=None,
        redoc_url=None,
        openapi_url=None,
    )
    factory = service_factory or build_assistant_service
    service_lock = threading.Lock()
    request_limiter = SlidingWindowRateLimiter(
        _positive_int_env("PERSONAX_API_REQUESTS_PER_MINUTE", 60),
        window_seconds=60.0,
    )

    def get_service() -> AssistantService:
        current = getattr(app.state, "assistant_service", None)
        if current is not None:
            return current
        with service_lock:
            current = getattr(app.state, "assistant_service", None)
            if current is None:
                current = factory()
                app.state.assistant_service = current
        return current

    def enforce_request_rate() -> None:
        decision = request_limiter.check("api-global")
        if decision.allowed:
            return
        raise HTTPException(
            status_code=status.HTTP_429_TOO_MANY_REQUESTS,
            detail={"code": "api_rate_limited", "message": "请求过于频繁，请稍后重试"},
            headers={"Retry-After": str(request_limiter.retry_seconds(decision))},
        )

    localized_schemas: dict[str, dict[str, Any]] = {}

    def localized_schema(language: str) -> dict[str, Any]:
        cached = localized_schemas.get(language)
        if cached is not None:
            return cached
        copy = _DOC_LANGUAGES[language]
        schema = get_openapi(
            title=copy["api_title"],
            version=API_VERSION,
            summary=copy["summary"],
            description=copy["description"],
            routes=app.routes,
        )
        _localize_openapi_schema(schema, language)
        localized_schemas[language] = schema
        return schema

    def default_openapi() -> dict[str, Any]:
        return localized_schema("zh-CN")

    app.openapi = default_openapi  # type: ignore[method-assign]

    @app.get("/", include_in_schema=False)
    def root_docs() -> RedirectResponse:
        return RedirectResponse(url="/docs/zh-CN", status_code=status.HTTP_307_TEMPORARY_REDIRECT)

    @app.get("/docs", include_in_schema=False)
    def docs_default() -> RedirectResponse:
        return RedirectResponse(url="/docs/zh-CN", status_code=status.HTTP_307_TEMPORARY_REDIRECT)

    @app.get("/docs/{language}", include_in_schema=False)
    def docs_by_language(language: str) -> HTMLResponse:
        if language not in _DOC_LANGUAGES:
            raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="不支持的文档语言")
        copy = _DOC_LANGUAGES[language]
        swagger_page = get_swagger_ui_html(
            openapi_url=f"/openapi/{language}.json",
            title=copy["page_title"],
            swagger_ui_parameters={
                "deepLinking": True,
                "displayRequestDuration": True,
                "persistAuthorization": True,
                "tryItOutEnabled": True,
            },
        )
        page = swagger_page.body.decode("utf-8")
        page = page.replace("<html>", f'<html lang="{copy["html_lang"]}">', 1)
        page = page.replace("<body>", f"<body>{_docs_navigation(language)}", 1)
        return HTMLResponse(
            page,
            headers={"Content-Language": language, "Cache-Control": "no-store"},
        )

    @app.get("/openapi/{language}.json", include_in_schema=False)
    def openapi_by_language(language: str) -> JSONResponse:
        if language not in _DOC_LANGUAGES:
            raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="不支持的文档语言")
        return JSONResponse(
            localized_schema(language),
            headers={"Content-Language": language},
        )

    @app.get("/favicon.ico", include_in_schema=False)
    def favicon() -> Response:
        return Response(status_code=status.HTTP_204_NO_CONTENT)

    @app.get("/healthz", response_model=HealthResponse, tags=["system"])
    def health() -> HealthResponse:
        return HealthResponse(
            status="ok",
            version=API_VERSION,
            api_token_required=bool(os.getenv("PERSONAX_API_TOKEN", "").strip()),
        )

    @app.get("/readyz", response_model=HealthResponse, tags=["system"])
    def ready() -> HealthResponse:
        try:
            get_service()
        except Exception as exc:  # noqa: BLE001
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail={
                    "code": "service_not_ready",
                    "message": "助手配置初始化失败",
                    "error_type": type(exc).__name__,
                },
            ) from None
        return HealthResponse(
            status="ready",
            version=API_VERSION,
            api_token_required=bool(os.getenv("PERSONAX_API_TOKEN", "").strip()),
        )

    @app.post(
        "/v1/assistant/reply",
        response_model=AssistantResponse,
        tags=["assistant"],
        dependencies=[Depends(_require_api_token), Depends(enforce_request_rate)],
    )
    def reply(payload: AssistantAPIRequest, response: Response) -> AssistantResponse:
        request = payload.to_core_request()
        try:
            result = get_service().reply(request)
        except Exception as exc:  # noqa: BLE001
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail={
                    "code": "assistant_unavailable",
                    "message": "助手暂时不可用，请根据 trace_id 查看本地日志",
                    "trace_id": request.trace_id,
                    "error_type": type(exc).__name__,
                },
                headers={"X-Trace-ID": request.trace_id},
            ) from None
        response.headers["X-Trace-ID"] = result.trace_id
        return result

    @app.post(
        "/v1/assistant/stream",
        response_class=StreamingResponse,
        responses={200: {"content": {"text/event-stream": {}}}},
        tags=["assistant"],
        dependencies=[Depends(_require_api_token), Depends(enforce_request_rate)],
    )
    def stream(payload: AssistantAPIRequest) -> StreamingResponse:
        request = payload.to_core_request()

        def events() -> Iterator[str]:
            try:
                answer_stream = get_service().reply_stream(request)
                for chunk in answer_stream:
                    yield _sse("token", {"text": str(chunk)})
                completed = getattr(answer_stream, "response", None)
                if completed is None:
                    raise RuntimeError("回答流结束但缺少最终响应")
                yield _sse("done", completed.model_dump(mode="json"))
            except GeneratorExit:
                raise
            except Exception as exc:  # noqa: BLE001
                yield _sse("error", {
                    "code": "assistant_stream_failed",
                    "message": "流式回答中断，请重试",
                    "trace_id": request.trace_id,
                    "error_type": type(exc).__name__,
                })

        return StreamingResponse(
            events(),
            media_type="text/event-stream",
            headers={
                "Cache-Control": "no-cache, no-transform",
                "X-Accel-Buffering": "no",
                "X-Trace-ID": request.trace_id,
            },
        )

    return app


app = create_app()


if __name__ == "__main__":
    import uvicorn

    uvicorn.run("api:app", host="127.0.0.1", port=8000, workers=1)
