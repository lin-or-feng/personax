class AssistantService(Protocol):
    """方便 API 测试替换真实模型，不扩散到核心编排层。"""

    def reply(self, request: AssistantRequest) -> AssistantResponse: ...

    def reply_stream(self, request: AssistantRequest) -> Any: ...


class HealthResponse(BaseModel):
    status: str
    version: str
    service: str = "personax-api"
    publish_api_exposed: bool = False
    api_token_required: bool = False


def _load_persona(path: Path | None = None) -> dict[str, Any]:
    target = path or ROOT / "config" / "persona.yaml"
    data = yaml.safe_load(target.read_text(encoding="utf-8")) or {}
    if not isinstance(data, dict):
        raise ValueError("persona 配置必须是 YAML 对象")
    return data


def build_assistant_service() -> AssistantOrchestrator:
    """构建单进程共享服务；Harness 限流不会被每个请求重置。"""

    load_env_file(ROOT / ".env")
    persona = _load_persona()
    harness = Harness(RuleConfig(**(persona.get("harness", {}) or {})))
    checkpoint_path = Path(os.getenv(
        "PERSONAX_ASSISTANT_DB",
        str(ROOT / "logs" / "assistant_checkpoints.sqlite3"),
    ))
    return AssistantOrchestrator(
        persona,
        harness=harness,
        checkpoint_store=AssistantCheckpointStore(checkpoint_path),
        prompt_path=ROOT / "config" / "assistant_prompts.yaml",
    )


def _require_api_token(
    credentials: Annotated[
        HTTPAuthorizationCredentials | None,
        Security(_BEARER),
    ] = None,
) -> None:
    expected = os.getenv("PERSONAX_API_TOKEN", "").strip()
    if not expected:
        return
    supplied = credentials.credentials if credentials is not None else ""
    scheme = credentials.scheme if credentials is not None else ""
    if scheme.lower() != "bearer" or not hmac.compare_digest(supplied, expected):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail={"code": "invalid_api_token", "message": "Bearer token 无效"},
            headers={"WWW-Authenticate": "Bearer"},
        )


def _sse(event: str, payload: Any) -> str:
    data = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    return f"event: {event}\ndata: {data}\n\n"


def _positive_int_env(name: str, default: int, *, maximum: int = 10_000) -> int:
    try:
        value = int(os.getenv(name, str(default)))
    except (TypeError, ValueError):
        return default
    return max(1, min(value, maximum))


def _localize_openapi_schema(schema: dict[str, Any], language: str) -> None:
    """只翻译说明文字，路径、字段名、SSE 事件等技术契约保持英文。"""

    for (path, method), translations in _OPERATION_DOCS.items():
        operation = schema.get("paths", {}).get(path, {}).get(method)
        if not isinstance(operation, dict):
            continue
        summary, description = translations[language]
        operation["summary"] = summary
        operation["description"] = description
        operation["tags"] = ["系统 / System" if path in {"/healthz", "/readyz"} else "助手 / Assistant"]
        validation_error = operation.get("responses", {}).get("422")
        if isinstance(validation_error, dict):
            validation_error["description"] = (
                "请求参数校验失败" if language == "zh-CN" else "Request validation failed"
            )

    request_schema = (
        schema.get("components", {})
        .get("schemas", {})
        .get("AssistantAPIRequest", {})
    )
    properties = request_schema.get("properties", {})
    for field_name, translations in _REQUEST_FIELD_DOCS.items():
        field_schema = properties.get(field_name)
        if isinstance(field_schema, dict):
            field_schema["description"] = translations[language]

    request_schema["examples"] = [{
        "question": (
            "请介绍 PersonaX 的 RAG 流程"
            if language == "zh-CN"
            else "Explain the PersonaX RAG pipeline"
        ),
        "thread_id": "demo-1",
        "use_knowledge": True,
    }]


